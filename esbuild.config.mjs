import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { promises as fsp } from 'node:fs';
import path from 'node:path';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
https://github.com/ai4pastor/obsidian-pdf-ocr
*/
`;

const prod = process.argv[2] === 'production';

// kordoc 의 선택 의존성(네이티브 애드온·ML·인쇄·MCP)은 옵시디언 번들에 넣지 않는다.
// 런타임에 이 모듈을 부르면 실패하고, kordoc 은 그 실패를 경고로 처리한다(문서 변환에는 쓰이지 않음).
const OPTIONAL_EXTERNALS = [
	'onnxruntime-node',
	'sharp',
	'@hyzyla/pdfium',
	'@huggingface/tokenizers',
	'@huggingface/transformers',
	'zxing-wasm',
	'zxing-wasm/reader',
	'puppeteer-core',
	'@napi-rs/canvas',
	'canvas',
	'@modelcontextprotocol/sdk',
];

const PDFJS_MAIN = /^pdfjs-dist\/legacy\/build\/pdf\.mjs$/;
const PDFJS_SHIM = path.resolve('src/local/pdfjsShim.mjs');

/**
 * kordoc 은 Node 전용 방식(createRequire(import.meta.url))으로 cfb 를 불러온다.
 * 하나로 묶은 플러그인 안에서는 import.meta.url 이 비어 있어 모듈 초기화 자체가 깨지므로(HWP 변환 불가),
 * cfb 만 돌려주는 작은 require 로 바꾼다. 다른 이름을 찾으면 오류를 던지고, 그 호출부는 kordoc 이 try/catch 로 감싸 둔 곳뿐이다.
 */
const kordocBundlePatch = {
	name: 'a4p-kordoc-bundle-patch',
	setup(build) {
		// esbuild 가 이름을 겹치지 않게 createRequire2·createRequire3 … 으로 바꿔 둔 것까지 잡는다
		const CREATE_REQUIRE_CALL = /\bcreateRequire\d*\(import\.meta\.url\)/g;
		build.onLoad({ filter: /[\\/]node_modules[\\/]kordoc[\\/]dist[\\/].*\.js$/ }, async (args) => {
			const source = await fsp.readFile(args.path, 'utf8');
			if (!CREATE_REQUIRE_CALL.test(source)) {
				return { contents: source, loader: 'js', resolveDir: path.dirname(args.path) };
			}
			CREATE_REQUIRE_CALL.lastIndex = 0;
			const patched =
				'import * as __a4pCfb from "cfb";\n' +
				'var __a4pCreateRequire = () => {\n' +
				'  const req = (name) => {\n' +
				'    if (name === "cfb") return __a4pCfb.default || __a4pCfb;\n' +
				'    throw new Error("A4P 문서 변환: 번들 밖 모듈을 불러올 수 없습니다 — " + name);\n' +
				'  };\n' +
				'  req.resolve = (name) => { throw new Error("A4P 문서 변환: 경로를 찾을 수 없습니다 — " + name); };\n' +
				'  return req;\n' +
				'};\n' +
				source.replace(CREATE_REQUIRE_CALL, '__a4pCreateRequire()');
			return { contents: patched, loader: 'js', resolveDir: path.dirname(args.path) };
		});
	},
};

/**
 * kordoc·플러그인이 부르는 pdf.js 를 src/local/pdfjsShim.mjs 로 돌린다.
 * 심(shim)은 getDocument 에 내장 한국어 CMap 을 넣어 주고, 나머지는 원본을 그대로 내보낸다.
 */
const pdfjsShimRedirect = {
	name: 'a4p-pdfjs-shim',
	setup(build) {
		build.onResolve({ filter: PDFJS_MAIN }, (args) => {
			if (path.resolve(args.importer) === PDFJS_SHIM) return undefined; // 심 자신은 원본을 가져간다
			return { path: PDFJS_SHIM };
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
		...builtinModules.map((name) => `node:${name}`),
		...OPTIONAL_EXTERNALS,
	],
	plugins: [kordocBundlePatch, pdfjsShimRedirect],
	format: 'cjs',
	target: 'es2020',
	logLevel: 'info',
	// kordoc 의 양식 템플릿 경로 계산(쓰지 않는 기능)이 import.meta 를 참조 — 비어 있어도 무방
	logOverride: { 'empty-import-meta': 'silent' },
	sourcemap: prod ? false : 'inline',
	minify: prod,
	legalComments: 'eof',
	treeShaking: true,
	metafile: prod,
	outfile: 'main.js',
});

if (prod) {
	const result = await context.rebuild();
	if (result.metafile) {
		await fsp.writeFile('meta.json', JSON.stringify(result.metafile));
	}
	await context.dispose();
	process.exit(0);
} else {
	await context.watch();
}
